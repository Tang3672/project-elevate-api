from app.services.adversarial_review_service import (
    run_adversarial_review,
    validate_adversarial_review,
    _extract_recommendations,
    _fallback_review,
    _CRITIC_SYSTEM,
)


class TestAdversarialReviewService:

    def test_critic_system_mentions_structural_risk(self):
        assert "structural_risk" in _CRITIC_SYSTEM.lower()

    def test_critic_system_is_separate_from_synthesis(self):
        # The critic must explicitly frame itself as adversarial — "not to agree" or "critic"
        assert "not to agree" in _CRITIC_SYSTEM.lower() or "critic" in _CRITIC_SYSTEM.lower(), \
            "Critic system must contain 'not to agree' or 'critic' to signal adversarial stance"
        # It must NOT instruct the model to agree unconditionally
        lower = _CRITIC_SYSTEM.lower()
        assert "your job is to agree" not in lower and "you should agree" not in lower, \
            "Critic system must not instruct the model to simply agree with the report"

    def test_extract_recommendations_from_next_steps(self):
        report = {
            "recommended_next_steps": [
                "File provisional patent on core IP",
                "Apply to NSF SBIR Phase I",
                "Run 10 structured PI interviews",
            ]
        }
        recs = _extract_recommendations(report, "wearable data logger")
        assert len(recs) >= 3
        assert "File provisional patent" in recs[0]

    def test_extract_recommendations_caps_at_max(self):
        report = {
            "recommended_next_steps": [f"Step {i}" for i in range(20)]
        }
        recs = _extract_recommendations(report, "wearable")
        from app.services.adversarial_review_service import _MAX_RECOMMENDATIONS
        assert len(recs) <= _MAX_RECOMMENDATIONS

    def test_fallback_review_includes_all_recs(self):
        recs = ["Step A", "Step B", "Step C"]
        result = _fallback_review(recs)
        assert len(result) == 3
        for item in result:
            assert "structural_risk" in item
            assert item["structural_risk"].strip() != ""

    def test_fallback_review_structural_risk_non_empty(self):
        result = _fallback_review(["Do X"])
        assert result[0]["structural_risk"].strip() != ""

    def test_run_adversarial_review_no_api_key_returns_fallback(self):
        import os
        orig = os.environ.pop("ANTHROPIC_API_KEY", None)
        try:
            report = {"recommended_next_steps": ["Apply to NSF SBIR", "Run PI interviews"]}
            result = _run(run_adversarial_review(report, "wearable data logger"))
            assert isinstance(result, list)
            assert len(result) >= 1
            for item in result:
                assert item.get("structural_risk", "").strip() != ""
        finally:
            if orig:
                os.environ["ANTHROPIC_API_KEY"] = orig

    def test_run_adversarial_review_empty_report_returns_empty(self):
        result = _run(run_adversarial_review({}, "wearable"))
        assert result == []

    def test_validate_adversarial_review_enforces_structural_risk(self):
        items = [
            {"recommendation": "Do X", "supporting_case": "...", "structural_risk": "",
             "disconfirming_evidence": "None", "what_would_change_this": "..."},
        ]
        validated = validate_adversarial_review(items)
        assert len(validated) == 1
        assert validated[0]["structural_risk"].strip() != ""

    def test_validate_adversarial_review_drops_items_without_rec(self):
        items = [
            {"recommendation": "", "structural_risk": "some risk"},
            {"recommendation": "Valid step", "structural_risk": "concrete risk"},
        ]
        validated = validate_adversarial_review(items)
        assert len(validated) == 1
        assert validated[0]["recommendation"] == "Valid step"

    def test_adversarial_review_field_on_pireport(self):
        from app.models.alignment import PIReport
        assert "adversarial_review" in PIReport.model_fields


