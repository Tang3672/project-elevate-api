class TestSegmentFitTable:

    def test_field_exists_on_pireport(self):
        from app.models.alignment import PIReport
        assert "segment_fit_table" in PIReport.model_fields

    def test_json_schema_mentions_explicit_non_target(self):
        from app.services.alignment_service import EXPERT_JSON_SCHEMA
        assert "Explicit non-target" in EXPERT_JSON_SCHEMA, \
            "S-03: schema must show 'Explicit non-target' as a valid stance value"

    def _parse_segment_table(self, rows):
        """Run the enforcement logic from _parse_expert_response."""
        from app.services.alignment_service import logger
        sft = [r for r in rows if isinstance(r, dict)]
        if sft and not any(
            "non-target" in (r.get("strategic_stance") or "").lower() for r in sft
        ):
            sft.append({
                "segment": "Segments outside primary buyer persona",
                "relative_fit": "Weak",
                "strategic_stance": "Explicit non-target",
                "rationale": "Enforced: every report must name at least one non-target segment.",
            })
        return sft

    def test_non_target_enforced_when_missing(self):
        rows = [
            {"segment": "Academic PIs", "relative_fit": "Strong", "strategic_stance": "Target", "rationale": "core buyer"},
            {"segment": "Hospitals", "relative_fit": "Moderate", "strategic_stance": "Selective", "rationale": "secondary"},
        ]
        result = self._parse_segment_table(rows)
        stances = [r["strategic_stance"] for r in result]
        assert any("non-target" in s.lower() for s in stances), \
            "Enforcement should add an Explicit non-target when missing"

    def test_non_target_not_duplicated_when_present(self):
        rows = [
            {"segment": "Academic PIs", "relative_fit": "Strong", "strategic_stance": "Target", "rationale": "core"},
            {"segment": "Enterprise IT", "relative_fit": "Weak", "strategic_stance": "Explicit non-target", "rationale": "not our buyer"},
        ]
        result = self._parse_segment_table(rows)
        non_target_count = sum(1 for r in result if "non-target" in r["strategic_stance"].lower())
        assert non_target_count == 1

    def test_empty_table_not_modified(self):
        result = self._parse_segment_table([])
        assert result == []


